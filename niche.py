def niche_score(keyword: str, context: str = "") -> tuple[int, str | None]:
    """트렌드 키워드가 니치에 맞는지 판정한다.

    점수는 **키워드 자체**로만 매긴다. 연관 헤드라인(context)은 차단어를
    찾는 용도로만 쓴다. 헤드라인까지 점수에 넣으면 "동료", "인사" 같은
    짧은 단어가 스포츠 기사에 우연히 걸려서 오판이 대량으로 생긴다.

    반환: (점수, 카테고리). 차단어가 있으면 (-1, None).
    """
    haystack = f"{keyword} {context}"
    for bad in BLOCK_TERMS:
        if bad in haystack:
            return -1, None

    best_score, best_cat = 0, None
    for cat, terms in NICHE_TERMS.items():
        hits = sum(1 for t in terms if t in keyword)
        if hits > best_score:
            best_score, best_cat = hits, cat
    return best_score, best_cat
