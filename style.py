"""이선생 네이버 원고 문체 규칙 (2026-11-27).

사용자: "글이 다 나의 문체가 아니라서 안 올리고 있었어."
11-22~27 직장생활 네이버 원고를 한 편도 올리지 않았다. 사용자가 직접 고쳐 올린 글과 비교해서 뽑은 차이:
  - 그랜드워커힐(11-21): 작성안백업 → 최종본에서 문단을 거의 한 줄 한 문장으로 끊고,
    억지 비유("그릇은 그대로 두고 담는 음식만 바꾼 셈이다")와 정리 멘트("한 줄로 줄이면 이렇다")를 지웠다.
  - 직접 쓴 글(크리에이터샵 오픈, 건강검진 ep09): 툭 던지는 위트, 괄호 속 한마디, 감상·교훈 마무리 없음.
  - 자동 원고: 후배 실수 → 커피 → "괜히 뿌듯했다 / 오히려 내가 배웠다" 같은 틀이 네 편 연속.
naver.py(직장생활)와 brand.py(브랜드시선) 둘 다 이 RULE 을 프롬프트에 넣는다.
견본은 data/naver_examples.md (사용자가 직접 쓰거나 다듬어 올린 완성본).
"""
from pathlib import Path

EXAMPLES = (Path(__file__).parent / "data" / "naver_examples.md").read_text(encoding="utf-8")

RULE = """[이선생 문체 — 사용자가 직접 고친 글에서 뽑은 규칙, 반드시 지킨다]
- 줄바꿈: 장면·도입·흐름을 바꾸는 대목은 **한 줄에 한 문장**으로 끊는다. 서너 문장을 한 문단에 붙이지 않는다.
  설명이 이어지는 정보 대목만 2~3문장 문단을 허용한다.
- 감상·교훈으로 끝맺지 않는다. 금지 예: 괜히 뿌듯했다, 오히려 내가 더 많이 배운 자리였다, 이 일을 계속하게 만드는 이유다,
  한 뼘씩 자라는 모습, 마음이 따뜻해졌다, 새삼 깨달았다. 마지막은 건조한 관찰 한 줄이나 사실로 닫는다.
- 비유를 정리하는 문장을 쓰지 않는다. 금지 예: ~한 셈이다(비유 요약), 한 줄로 줄이면 이렇다, 결국 ~이다(총정리),
  이 전략을 떠받치는 건 결국 ~다. 비유는 한 번 던지고 설명하지 않는다.
- 위트는 툭 던진다: 괄호 속 한마디 (손 들어 보세요.), 짧은 혼잣말 (네이버 일 잘하네.), 그런데! 같은 한 단어 전환.
  한 글에 두세 번.
- 감정을 설명하지 않는다. 당황했다·미안해졌다·뿌듯했다 대신 그 순간의 행동이나 말 한마디로 보여 준다.
- 장면은 짧게: 도입 장면은 4~6줄 안에서 끝내고 본론(사실·요령)으로 간다. 한 장면을 글 끝까지 끌고 가는 이야기책 구성 금지.
  처음 장면 속 인물은 끝에 한 번만 짧게 다시 나온다 (예: 후배는 통화가 끝나자마자 검진센터에 전화를 걸었다.).
- 후배 실수 → 불러서 커피 → 조언 → 후배 성장 틀을 쓰지 않는다. 인물이 그 뒤로 달라졌다·잘 됐다·제일 ~한 사람이 됐다로 끝내지 않는다. 인물도 후배만 쓰지 말고 남편, 동료 과장, 인사팀,
  혼자 본 장면, 뉴스·공지 하나로 시작하는 등 매번 다르게.
- 대사는 따옴표 없이 간접화법으로 (~냐고 물었다, ~라는 거다). 꼭 필요할 때만 짧은 대사 한 줄.
- 마지막 안내도 평어체: 이웃 추가해 두면 ~ 바로 보일 거다 / 놀러 오시라. **~하세요, ~해 주세요 같은 존댓말 금지.**
  (Q. 댓글 질문 한 줄만 존댓말 허용: Q. 올해 건강검진, 받으셨나요?)
- 목록은 '· ' 로 시작하는 짧은 줄로 쓴다."""


def prompt_block() -> str:
    """프롬프트에 넣을 규칙 + 문체 견본."""
    return (RULE + "\n\n[문체 견본 — 사용자가 직접 쓰거나 다듬어 올린 완성본. 리듬·줄바꿈·위트·끝맺음을 따르고, 내용·구성은 베끼지 않는다]\n"
            + EXAMPLES)
